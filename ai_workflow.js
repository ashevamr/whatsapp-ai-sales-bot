  // Prompt rules reduce verbosity; this guard prevents a rare model miss from
  // reaching a customer as a catalogue-length WhatsApp message.
  stripCustomerFileReferences(reply) {
    return String(reply || '')
      // Handles bracketed and unbracketed file names, including a line break
      // before the extension (for example "foura main picture.\njpeg").
      .replace(/\[?\s*[a-z0-9][a-z0-9 _+.\r\n-]{0,100}\.\s*(?:jpe?g|png|pdf)\s*\]?/gi, '')
      .replace(/\n{3,}/g, '\n\n')
      .trim();
  }

  // The manager uses only 😊 and 💐, never more than one per message. The prompt
  // asks for this; this guard enforces it if the model slips.
  limitEmojis(text) {
    let allowedKept = false;
    return String(text || '')
      .replace(/[0-9#*]️?⃣/gu, '')
      .replace(/\p{Regional_Indicator}{2}/gu, '')
      .replace(/\p{Extended_Pictographic}(?:️|‍\p{Extended_Pictographic}|[\u{1F3FB}-\u{1F3FF}])*/gu, emoji => {
        if ((emoji === '😊' || emoji === '💐') && !allowedKept) {
          allowedKept = true;
          return emoji;
        }
        return '';
      })
      .replace(/[^\S\n]+(?=\n|$)/g, '')
      .replace(/(^|\n)[^\S\n]+/g, '$1')
      .replace(/[^\S\n]+([.,!?…])/g, '$1')
      .replace(/[^\S\n]{2,}/g, ' ');
  }

  formatSalesReply(reply) {
    const { protectedText, restoreUrls } = protectUrls(reply);
    const text = this.limitEmojis(protectedText)
      .replace(/\r\n?/g, '\n')
      .replace(/\[?\s*[a-z0-9][a-z0-9 _+.\r\n-]{0,100}\.\s*(?:jpe?g|png|pdf)\s*\]?/gi, '')
      .replace(/[^\S\n]+/g, ' ')
      .replace(/\n{3,}/g, '\n\n')
      .trim();
    // A handover is only the short acknowledgement: anything the model adds
    // after it (another question, a sales pitch) must not reach the customer.
    if (text.startsWith('[HANDOVER]')) return restoreUrls(text.split('\n')[0].trim());
    if (!text || text === 'HANDOVER') return restoreUrls(text);

    // Keep a trailing smile ("?😊", "пожалуйста)") attached to its sentence.
    const sentences = text.match(/[^.!?…]+[.!?…]+(?:[^\S\n]*(?:😊|💐|\)))*|[^.!?…]+$/gu) || [text];
    const seenSentences = new Set();
    const cleaned = sentences
      .map(sentence => sentence.trim())
      .filter(Boolean)
      .filter(sentence => {
        // Gemini can occasionally repeat a complete sentence while preserving
        // different line breaks. Never deliver the same substantial sentence
        // twice in a single WhatsApp bubble.
        const key = sentence
          .toLowerCase()
          .replace(/[\p{P}\p{S}\s]+/gu, '');
        if (key.length < 12 || !seenSentences.has(key)) {
          if (key.length >= 12) seenSentences.add(key);
          return true;
        }
        return false;
      });
    // A model can hit its token cap in the middle of a fourth sentence. Never
    // show that fragment to a customer: it reads like the bot has stopped
    // listening. Keep complete sentences and offer one natural next step.
    // A closing ")" (a smile) or an allowed emoji is a complete ending too.
    const replyWasCutMidSentence = !/[.!?…)]$/.test(text.replace(/\s*(?:😊|💐)$/u, ''));
    const completeSentences = replyWasCutMidSentence && cleaned.length > 1
      ? cleaned.slice(0, -1)
      : cleaned;
    const separator = text.includes('\n') ? '\n' : ' ';
    const maxChars = 650;
    const maxSentences = 5;
    // A short, complete reply keeps the natural sentence order.
    const ordered = completeSentences.filter((sentence, index, all) =>
      all.findIndex(other => other.toLowerCase() === sentence.toLowerCase()) === index);
    if (!replyWasCutMidSentence && ordered.length <= maxSentences
      && ordered.join(separator).length <= maxChars) {
      return restoreUrls(ordered.join(separator).trim());
    }
    const lastQuestion = [...completeSentences].reverse().find(sentence => /\?(?:\s*(?:😊|💐|\)))*$/u.test(sentence));
    const hasKazakhLetters = /[әғқңөұүһі]/i.test(text);
    const completionQuestion = hasKazakhLetters
      ? 'Осы модель туралы толығырақ айтайын ба?'
      : 'Хотите, я расскажу подробнее об этой модели?';
    const requiredQuestion = replyWasCutMidSentence && !lastQuestion ? completionQuestion : lastQuestion;
    const body = requiredQuestion
      ? completeSentences.filter(sentence => sentence !== requiredQuestion)
      : completeSentences;
    const selected = [];
    const bodyBudget = requiredQuestion
      ? maxChars - requiredQuestion.length - separator.length
      : maxChars;

    for (const sentence of body) {
      const nextLength = selected.length
        ? selected.join(separator).length + separator.length + sentence.length
        : sentence.length;
      if (selected.length >= maxSentences - (requiredQuestion ? 1 : 0) || nextLength > bodyBudget) break;
      selected.push(sentence);
    }

    if (requiredQuestion && selected.join(separator).length + separator.length + requiredQuestion.length <= maxChars) {
      selected.push(requiredQuestion);
    }

    // Avoid a raw character slice here. A complete first sentence is always
    // clearer than a longer message cut in the middle of a word.
    const concise = selected.join(separator).trim();
    if (concise) {
      return restoreUrls(concise);
    }
    return restoreUrls(completeSentences[0] || completionQuestion);
  }

  splitIntoBubbles(text) {
    if (!text || typeof text !== 'string') return [];
    const { protectedText, restoreUrls } = protectUrls(text);
    const trimmed = protectedText.trim();
    if (!trimmed) return [];
    if (trimmed.startsWith('[HANDOVER]') || trimmed === 'HANDOVER') {
      return [restoreUrls(trimmed)];
    }
    // The approved product menu is deliberately a single WhatsApp message.
    // Splitting it makes the choices look like separate unsolicited replies.
    if (trimmed === this.buildWelcomeMessage()) {
      return [restoreUrls(trimmed)];
    }

    // Разделение по абзацам (двойной перенос строки)
    const paragraphs = trimmed
      .split(/\n\s*\n+/)
      .map(p => p.trim())
      .filter(Boolean);

    if (paragraphs.length > 1 && paragraphs.length <= 3) {
      return paragraphs.map(restoreUrls);
    }

    if (paragraphs.length > 3) {
      const bubbles = [];
      let current = '';
      for (const p of paragraphs) {
        if (!current) {
          current = p;
        } else if (bubbles.length < 2 && (current.length + p.length < 320)) {
          current += '\n\n' + p;
        } else {
          bubbles.push(current);
          current = p;
        }
      }
      if (current) bubbles.push(current);
      return bubbles.map(restoreUrls);
    }

    // Если один длинный абзац с завершающим вопросом — делим на утверждение и вопрос
    const sentences = trimmed.match(/[^.!?…]+[.!?…]+|[^.!?…]+$/g) || [trimmed];
    if (sentences.length >= 2 && trimmed.length > 120) {
      const lastSentence = sentences[sentences.length - 1].trim();
      const firstPart = sentences.slice(0, -1).join(' ').trim();
      if (lastSentence.endsWith('?') && firstPart.length > 0) {
        return [restoreUrls(firstPart), restoreUrls(lastSentence)];
      }
    }

    return [restoreUrls(trimmed)];
  }

