function protectUrls(value) {
  const urls = [];
  const protectedText = String(value || '').replace(/https?:\/\/[^\s<>"']+/gi, url => {
    const token = `VODELURLTOKEN${urls.length}END`;
    urls.push(url);
    return token;
  });
  return {
    protectedText,
    restoreUrls: valueToRestore => String(valueToRestore || '').replace(/VODELURLTOKEN(\d+)END/g, (token, index) => urls[Number(index)] || token)
  };
}

