  async generateResponse(chatHistory, lastMessageContent, options = {}) {
    const skipFirstLeadWelcome = Boolean(options.skipFirstLeadWelcome);
    const checkoutAuthorized = Boolean(options.checkoutAuthorized);
    // ВАЖНО: Берем только ПРЕДЫДУЩИЕ сообщения истории для startChat,
    // так как последнее сообщение клиента передается отдельно через sendMessage!
    // Сравниваем по индексу с конца, чтобы избежать ложных совпадений при повторных текстах.
    let previousHistory = chatHistory;
    if (chatHistory.length > 0) {
      const lastMsg = chatHistory[chatHistory.length - 1];
      if (lastMsg.sender === 'user' && lastMsg.text === lastMessageContent) {
        previousHistory = chatHistory.slice(0, -1);
      }
    }

    const formattedHistory = [];

    for (const msg of previousHistory) {
      const role = msg.sender === 'user' ? 'user' : 'model';
      if (formattedHistory.length > 0 && formattedHistory[formattedHistory.length - 1].role === role) {
        formattedHistory[formattedHistory.length - 1].parts[0].text += `\n${msg.text}`;
      } else {
        formattedHistory.push({
          role: role,
          parts: [{ text: msg.text }]
        });
      }
    }

    // Gemini API требует строгого чередования: user -> model -> user -> model.
    // Так как sendMessage() отправляет сообщение от 'user', история ОБЯЗАНА заканчиваться на 'model'.
    // Если история заканчивается на 'user', мы забираем этот текст и добавляем к текущему сообщению.
    while (formattedHistory.length > 0 && formattedHistory[formattedHistory.length - 1].role === 'user') {
      const poppedUser = formattedHistory.pop();
      lastMessageContent = poppedUser.parts[0].text + "\n" + lastMessageContent;
    }

    // Если после этого история начинается не с 'user' (а должна!), добавляем фиктивный 'user' в начало
    if (formattedHistory.length > 0 && formattedHistory[0].role !== 'user') {
      formattedHistory.unshift({
        role: 'user',
        parts: [{ text: "Здравствуйте! Я хочу проконсультироваться по фильтрам VODEL." }]
      });
    }

    // Расчет текущего времени по часовому поясу Астаны (GMT+5)
    const now = new Date();
    const astanaOffsetMs = 5 * 60 * 60 * 1000;
    const utcMs = now.getTime() + (now.getTimezoneOffset() * 60000);
    const astanaDate = new Date(utcMs + astanaOffsetMs);
    const astanaHours = astanaDate.getHours();
    const astanaMinutes = astanaDate.getMinutes();
    const timeStr = `${String(astanaHours).padStart(2, '0')}:${String(astanaMinutes).padStart(2, '0')}`;

    const timeGreeting = this.getTimeGreeting(astanaHours);

    const commercialPolicy = getCommercialConversationPolicy(chatHistory, lastMessageContent);
    // A follow-up such as "а размеры?" no longer names the model, so keep the
    // facts of the catalog model the dialogue is about.
    const activeCatalogProduct = resolveLatestCatalogProduct(chatHistory, lastMessageContent);
    const commercialFacts = getCommercialFactsForPrompt(
      commercialPolicy,
      [lastMessageContent, activeCatalogProduct?.name].filter(Boolean).join('\n')
    );
    const logisticsFacts = getLogisticsForPrompt(commercialPolicy, astanaHours);

    if (this.shouldAnswerFouraPriceObjection(lastMessageContent)) {
      return this.buildFouraPriceObjectionAnswer();
    }

    if (commercialPolicy.eligibleForAlkalineCashOffer) {
      return this.buildEligibleG75CashOffer();
    }

    // The existing welcome is deliberately preserved verbatim. The concise
    // conversational rules apply from the customer's next message onward.
    const hasAssistantReply = previousHistory.some(message => message.sender !== 'user');
    if (!hasAssistantReply && this.shouldClarifyRuralTanklessRequest(lastMessageContent)) {
      return this.buildRuralTanklessReply();
    }

    // A general Instagram-ad question is not a model choice. Do not guess a
    // product, price, or attachment before the customer says tank/no-tank.
    if (!skipFirstLeadWelcome && !hasAssistantReply && !this.hasExplicitFilterPreference(lastMessageContent)) {
      return this.buildWelcomeMessage();
    }

    if (!skipFirstLeadWelcome && !hasAssistantReply && this.isPrefilledInstagramLead(lastMessageContent)) {
      return this.buildWelcomeMessage();
    }

    if (this.shouldExplainFilterDifference(lastMessageContent)) {
      return this.buildFilterTypeComparison();
    }

    if (this.shouldAnswerTanklessPrice(lastMessageContent)) {
      return this.buildTanklessPriceAnswer();
    }

    // The fixed schedule covers only G75 and FOURA; for another catalog model
    // (e.g. the advertised RO-H015) the model answers from that model's facts.
    const discussesOtherCatalogModel = activeCatalogProduct
      && !['alkaline_g75', 'foura_600gpd'].includes(activeCatalogProduct.id);
    if (this.shouldAnswerServiceCost(lastMessageContent) && !discussesOtherCatalogModel) {
      return this.buildServiceCostAnswer();
    }

    if (!this.genAI) {
      console.log('Gemini API Key не настроен в .env. Передаём нестандартный запрос оператору.');
      return this.buildSafeFallbackReply(chatHistory, lastMessageContent, { skipFirstLeadWelcome });
    }

    const checkoutStateInstruction = checkoutAuthorized
      ? 'СОСТОЯНИЕ CHECKOUT: клиент явно подтвердил покупку. Можно запросить одну недостающую деталь заказа, но адрес нельзя спрашивать повторно.'
      : 'СОСТОЯНИЕ CHECKOUT: покупка НЕ подтверждена. Запрещено спрашивать адрес, дату/время установки или предлагать платный смеситель. Отвечай на текущий вопрос и помогай выбрать.';
    const dynamicSystemInstruction = `${CONCISE_SALES_INSTRUCTION}\n\n${commercialFacts}\n\n${logisticsFacts}\n\n${checkoutStateInstruction}\n\nТекущее время Астаны (GMT+5): ${timeStr}. При первом приветствии используй: "${timeGreeting}".`;

    for (const modelName of this.modelsToTry) {
      try {
        const model = this.genAI.getGenerativeModel({
          model: modelName,
          systemInstruction: `${dynamicSystemInstruction}\n${REPLY_OUTPUT_GUARDS}`,
        }, { timeout: 8000 });

        const chat = model.startChat({
          history: formattedHistory,
          generationConfig: {
            temperature: 0.3,
            maxOutputTokens: 220,
          }
        });

        const result = await chat.sendMessage(lastMessageContent);
        return this.formatSalesReply(result.response.text());
      } catch (error) {
        const msg = error.message || '';
        if (msg.includes('429') || msg.includes('Quota')) {
          console.warn(`⚠️ Модель ${modelName} превысила лимит запросов (429). Пробуем следующую модель...`);
        } else {
          console.error(`Ошибка Gemini API (${modelName}):`, msg);
        }
      }
    }

    // Three bounded attempts are enough; do not repeat the whole chain and
    // block the customer's queue for another minute during a provider outage.
    return this.buildSafeFallbackReply(chatHistory, lastMessageContent, { skipFirstLeadWelcome });
  }

