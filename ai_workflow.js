  async executeWithFallback(fn) {
    if (!this.genAI) return null;
    let lastErr = null;

    for (const modelName of this.modelsToTry) {
      for (let attempt = 0; attempt < 2; attempt++) {
        try {
          const model = this.genAI.getGenerativeModel({ model: modelName }, { timeout: 8000 });
          return await fn(model);
        } catch (err) {
          lastErr = err;
          const msg = err.message || '';
          if (msg.includes('429') || msg.includes('Quota')) {
            console.warn(`⚠️ ${modelName} rate limited. Переключение на запасную модель...`);
            break; // Переходим к следующей модели в цепочке
          } else {
            console.error(`Ошибка Gemini API (${modelName}):`, msg);
            break;
          }
        }
      }
    }
    throw lastErr;
  }

